function runSync() {
  console.log('===============================================================');
  console.log('   MEDEX & AROGGA PHARMACEUTICAL DATA SYNCHRONIZER (ETL)       ');
  console.log('===============================================================');
  console.log(`[INFO] Processing ${BANGLADESH_PHARMA_SEED_RECORDS.length} master pharmaceutical entries...`);

  const outputDir = path.resolve(__dirname, '../data');
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  const jsonOutputPath = path.join(outputDir, 'medex_arogga_catalog.json');
  const csvOutputPath = path.join(outputDir, 'medex_arogga_catalog.csv');

  // Format into PMS Database Schema
  const standardizedCatalog = BANGLADESH_PHARMA_SEED_RECORDS.map((item, index) => ({
    name: item.name,
    genericName: item.genericName,
    category: item.category,
    specialSegment: item.specialSegment,
    medicineType: item.medicineType,
    drugClass: item.drugClass,
    dosageForm: item.dosageForm,
    strength: item.strength,
    manufacturer: item.manufacturer,
    unit: item.unit,
    unitsPerBox: item.unitsPerBox,
    reorderLevel: 50,
    rackLocation: item.rackLocation,
    isColdChain: item.isColdChain,
    packSize: item.packSize,
    description: item.description,
    requiresPrescription: item.requiresPrescription,
    isAntibiotic: item.isAntibiotic,
    isNarcotic: item.isNarcotic,
    barcode: `890${(1000000 + index).toString()}`,
    sellingPrice: item.sellingPrice,
    purchasePrice: item.purchasePrice,
    quantityInStock: item.isColdChain ? 40 : 150
  }));

  // Write JSON Catalog
  fs.writeFileSync(jsonOutputPath, JSON.stringify(standardizedCatalog, null, 2), 'utf-8');
  console.log(`[SUCCESS] Wrote JSON catalog to: ${jsonOutputPath}`);

  // Write CSV Catalog
  const csvHeader = 'name,genericName,category,specialSegment,medicineType,dosageForm,strength,manufacturer,unit,unitsPerBox,packSize,sellingPrice,purchasePrice,isColdChain,requiresPrescription,isAntibiotic,isNarcotic,rackLocation,drugClass\n';
  const csvRows = standardizedCatalog.map((m) => 
    `"${m.name}","${m.genericName}","${m.category}","${m.specialSegment}","${m.medicineType}","${m.dosageForm}","${m.strength}","${m.manufacturer}","${m.unit}",${m.unitsPerBox},"${m.packSize}",${m.sellingPrice},${m.purchasePrice},${m.isColdChain},${m.requiresPrescription},${m.isAntibiotic},${m.isNarcotic},"${m.rackLocation}","${m.drugClass}"`
  ).join('\n');

  fs.writeFileSync(csvOutputPath, csvHeader + csvRows, 'utf-8');
  console.log(`[SUCCESS] Wrote CSV catalog to: ${csvOutputPath}`);

  // Summary Metrics
  const segmentStats = {};
  let coldChainCount = 0;
  let antibioticCount = 0;
  let narcoticCount = 0;

  standardizedCatalog.forEach((m) => {
    segmentStats[m.specialSegment] = (segmentStats[m.specialSegment] || 0) + 1;
    if (m.isColdChain) coldChainCount++;
    if (m.isAntibiotic) antibioticCount++;
    if (m.isNarcotic) narcoticCount++;
  });

  console.log('\n--- DATASET COMPLIANCE METRICS ---');
  console.table(segmentStats);
  console.log(`Cold Chain Biologicals (2°C - 8°C): ${coldChainCount}`);
  console.log(`Antibiotic Stewardship Items:     ${antibioticCount}`);
  console.log(`Narcotics / Schedule G Items:     ${narcoticCount}`);
  console.log('----------------------------------\n');
  console.log('✓ ETL Sync complete. Catalog files ready for PMS database import.');
}

runSync();
